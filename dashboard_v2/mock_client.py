class MockAuditClient:
    def __init__(self) -> None:
        self._config = Config()
        self._runs: Dict[str, RunState] = {}
        self._ground_truth: Dict[str, Dict[str, float]] = {}
        self._reviews: Dict[str, ReviewItem] = {}
        self._audit_log: List[AuditEntry] = []

    def get_config(self) -> Config:
        return self._config.model_copy()

    def update_config(self, config: Config) -> Config:
        self._config = config.model_copy()
        return self._config.model_copy()

    def start_run(self, ticker: str, fault_switch: bool = False) -> str:
        clean_ticker = ticker.upper().strip()
        if clean_ticker not in SAMPLE_FILINGS:
            raise ValueError(f"Unsupported sample ticker: {clean_ticker}")

        template = deepcopy(SAMPLE_FILINGS[clean_ticker])
        thread_id = f"mock-{clean_ticker.lower()}-{uuid4().hex[:6]}"
        metrics: List[ExtractedMetric] = []
        gt_map: Dict[str, float] = {}
        flag_reasons: Dict[str, List[str]] = {}

        for raw_m in template["metrics"]:
            val = float(raw_m["value"])
            if fault_switch and raw_m["metric_name"] == "Total Liabilities":
                val = val * 1.15
            gt_map[raw_m["metric_name"]] = float(raw_m["ground_truth"])

            reasons: List[str] = []
            if raw_m["confidence"] < self._config.confidence_threshold:
                reasons.append(
                    f"Confidence {raw_m['confidence']:.2f} below threshold {self._config.confidence_threshold:.2f}"
                )

            prior = float(raw_m["prior_value"])
            if prior > 0:
                yoy_change = abs(val - prior) / prior
                if yoy_change > self._config.year_on_year_threshold:
                    reasons.append(
                        f"YoY change {yoy_change * 100:.1f}% exceeds {self._config.year_on_year_threshold * 100:.0f}% threshold"
                    )

            flag_reasons[raw_m["metric_name"]] = reasons
            metrics.append(
                ExtractedMetric(
                    company=template["company_name"],
                    metric_name=raw_m["metric_name"],
                    value=val,
                    period_end=template["period_end"],
                    fiscal_label=template["fiscal_label"],
                    unit_scale="USD",
                    raw_text=raw_m["raw_text"],
                    source_snippet=raw_m["source_snippet"],
                    source_location=raw_m["source_location"],
                    extractor=raw_m["extractor"],
                    confidence=raw_m["confidence"],
                    confidence_signals=raw_m["confidence_signals"],
                    status="FLAGGED" if reasons else "APPROVED",
                )
            )

        by_name = {m.metric_name: m for m in metrics}
        assets = by_name["Total Assets"].value
        liab_plus_eq = by_name["Total Liabilities"].value + by_name["Shareholders' Equity"].value
        diff_ratio = abs(assets - liab_plus_eq) / max(assets, 1.0)
        eq_passed = diff_ratio <= self._config.equation_tolerance

        if not eq_passed:
            eq_msg = (
                f"Accounting equation mismatch: Assets ${assets / 1e9:.2f}B != "
                f"Liabilities + Equity ${liab_plus_eq / 1e9:.2f}B ({diff_ratio * 100:.2f}% diff)"
            )
            for m_name in ("Total Assets", "Total Liabilities", "Shareholders' Equity"):
                flag_reasons[m_name].append(eq_msg)
                by_name[m_name].status = "FLAGGED"
        else:
            eq_msg = f"Assets (${assets / 1e9:.2f}B) equal Liabilities + Equity (${liab_plus_eq / 1e9:.2f}B)."

        seg_info = template["segment_check"]
        if seg_info["status"] == "FAILED":
            flag_reasons["Revenue"].append(seg_info["reason"])
            by_name["Revenue"].status = "FLAGGED"

        yoy_failed_metrics = [
            m.metric_name
            for m in metrics
            if any("YoY change" in r for r in flag_reasons[m.metric_name])
        ]

        validations = [
            ValidationResult(
                check_name="Accounting Equation",
                status="PASSED" if eq_passed else "FAILED",
                reason=eq_msg,
                metrics_involved=["Total Assets", "Total Liabilities", "Shareholders' Equity"],
            ),
            ValidationResult(
                check_name="Segment Sum",
                status=seg_info["status"],
                reason=seg_info["reason"],
                metrics_involved=["Revenue"],
            ),
            ValidationResult(
                check_name="Year-on-Year Variance",
                status="FAILED" if yoy_failed_metrics else "PASSED",
                reason=(
                    f"Threshold exceeded on: {', '.join(yoy_failed_metrics)}."
                    if yoy_failed_metrics
                    else f"All metrics within {self._config.year_on_year_threshold * 100:.0f}% YoY threshold."
                ),
                metrics_involved=yoy_failed_metrics or [m.metric_name for m in metrics],
            ),
        ]

        created_ts = _utc_now()
        has_pending = False
        for m in metrics:
            if flag_reasons[m.metric_name]:
                has_pending = True
                rev_id = f"rev-{uuid4().hex[:8]}"
                self._reviews[rev_id] = ReviewItem(
                    id=rev_id,
                    thread_id=thread_id,
                    metric=m.metric_name,
                    reason=" | ".join(flag_reasons[m.metric_name]),
                    status="PENDING",
                    created_at=created_ts,
                )

        self._ground_truth[thread_id] = gt_map
        self._runs[thread_id] = RunState(
            thread_id=thread_id,
            ticker=clean_ticker,
            company_name=template["company_name"],
            workflow_status="PAUSED_FOR_REVIEW" if has_pending else "COMPLETED",
            data_source="SAMPLE",
            fault_injected=fault_switch,
            metrics=metrics,
            validations=validations,
        )
        return thread_id

    def get_run(self, thread_id: str) -> RunState:
        if thread_id not in self._runs:
            raise KeyError(f"Unknown run thread_id: {thread_id}")
        return self._runs[thread_id].model_copy(deep=True)

    def list_reviews(
        self,
        status: Literal["PENDING", "DONE"],
        thread_id: Optional[str] = None,
    ) -> List[ReviewItem]:
        items = [r.model_copy() for r in self._reviews.values() if r.status == status]
        if thread_id:
            items = [r for r in items if r.thread_id == thread_id]
        return items

    def submit_decision(
        self,
        review_id: str,
        action: Literal["APPROVED", "CORRECTED", "REJECTED"],
        corrected_value: Optional[float],
        notes: str,
        reviewer_id: str,
    ) -> ReviewItem:
        if review_id not in self._reviews:
            raise KeyError(f"Unknown review_id: {review_id}")
        review = self._reviews[review_id]
        if review.status == "DONE":
            raise ValueError("Review item already completed.")

        run = self._runs[review.thread_id]
        target_metric = next(m for m in run.metrics if m.metric_name == review.metric)
        original_val = target_metric.value

        if action == "APPROVED":
            final_val: Optional[float] = original_val
            target_metric.status = "APPROVED"
        elif action == "CORRECTED":
            if corrected_value is None:
                raise ValueError("Corrected value is required for CORRECTED action.")
            final_val = float(corrected_value)
            target_metric.value = final_val
            target_metric.status = "APPROVED"
        else:
            final_val = None
            target_metric.status = "REJECTED"

        review.status = "DONE"
        self._audit_log.append(
            AuditEntry(
                audit_id=f"aud-{uuid4().hex[:8]}",
                thread_id=run.thread_id,
                company=run.company_name,
                metric=review.metric,
                original_value=original_val,
                final_value=final_val,
                decision=action,
                reviewer_notes=notes.strip(),
                reviewer_id=reviewer_id.strip() or "reviewer_1",
                simulated=run.fault_injected,
                timestamp=_utc_now(),
            )
        )

        remaining = [
            r for r in self._reviews.values() if r.thread_id == run.thread_id and r.status == "PENDING"
        ]
        if not remaining:
            run.workflow_status = "COMPLETED"

        return review.model_copy()

    def get_audit_log(self, thread_id: Optional[str] = None) -> List[AuditEntry]:
        entries = [e.model_copy() for e in self._audit_log]
        if thread_id:
            entries = [e for e in entries if e.thread_id == thread_id]
        return entries

    def get_report(self, thread_id: str) -> ReportResponse:
        run = self.get_run(thread_id)
        gt_map = self._ground_truth.get(thread_id, {})
        rows: List[MetricAccuracyRow] = []
        accurate_count = 0

        for m in run.metrics:
            gt = gt_map.get(m.metric_name, m.value)
            err_pct = (abs(m.value - gt) / gt * 100.0) if gt else 0.0
            is_acc = err_pct <= 0.5 and m.status != "REJECTED"
            if is_acc:
                accurate_count += 1
            rows.append(
                MetricAccuracyRow(
                    metric_name=m.metric_name,
                    extracted_value=m.value,
                    ground_truth_value=gt,
                    error_pct=round(err_pct, 2),
                    accurate=is_acc,
                )
            )

        total_metrics = max(len(run.metrics), 1)
        escalated_reviews = [r for r in self._reviews.values() if r.thread_id == thread_id]
        escalated_count = len(escalated_reviews)
        auto_approved_count = len(run.metrics) - escalated_count

        genuine_escalations = 0
        for r in escalated_reviews:
            m_obj = next(m for m in run.metrics if m.metric_name == r.metric)
            gt = gt_map.get(r.metric, m_obj.value)
            had_error = abs(m_obj.value - gt) / max(gt, 1.0) > 0.005
            if had_error or "FAILED" in r.reason or "mismatch" in r.reason or "segment" in r.reason.lower():
                genuine_escalations += 1

        esc_precision = (genuine_escalations / escalated_count * 100.0) if escalated_count else 100.0

        return ReportResponse(
            thread_id=thread_id,
            company=run.company_name,
            extraction_accuracy_pct=round(accurate_count / total_metrics * 100.0, 1),
            escalation_precision_pct=round(esc_precision, 1),
            auto_approved_count=auto_approved_count,
            escalated_count=escalated_count,
            per_metric_accuracy=rows,
        )